export function trueEngineSlugs() {
  return Object.keys(ENGINE_ARTIFACTS).sort();
}

export function isTrueEngineSlug(slug) {
  return Boolean(ENGINE_ARTIFACTS[String(slug || "").toLowerCase()]);
}

export async function digestConcatenated(parts) {
  const encoder = new TextEncoder();
  let total = 0;
  const chunks = [];
  for (const part of parts) {
    const bytes = typeof part === "string" ? encoder.encode(part) : part;
    chunks.push(bytes);
    total += bytes.byteLength;
  }
  const out = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    out.set(chunk, offset);
    offset += chunk.byteLength;
  }
  const hex = await sha256Hex(out);
  out.fill(0);
  return hex;
}

export async function digestArtifactBytes(fileBytesByPath) {
  const paths = Object.keys(fileBytesByPath).sort();
  const parts = [];
  for (const path of paths) {
    parts.push(new TextEncoder().encode(path + "\n"));
    parts.push(fileBytesByPath[path]);
    parts.push(new TextEncoder().encode("\n"));
  }
  return digestConcatenated(parts);
}

export function embeddedDigest(slug) {
  const key = String(slug || "").toLowerCase();
  return ENGINE_DIGESTS[key] || null;
}
