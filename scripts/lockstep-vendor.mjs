/**
 * AZ-LOCKSTEP-1.0 vendor: copy the shared contract + design source into a leg checkout and write
 * its pin.  node scripts/lockstep-vendor.mjs <path to azinterface|azos checkout>
 * The leg's own npm test re-hashes every vendored file against LOCKSTEP.pin.json.
 * Author: Aziel Eliab.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const leg = process.argv[2];
if (!leg) throw new Error("usage: lockstep-vendor.mjs <leg checkout>");
const dest = `${leg}/workers/download-tracker`;
mkdirSync(`${dest}/vendor/lockstep`, { recursive: true });
const files = {
  "vendor/lockstep/consumer.js": "src/lockstep/consumer.js",
  "vendor/lockstep/tokens-css.js": "src/lockstep/tokens-css.js",
  "vendor/lockstep/tokens.json": "design/tokens.json",
  "vendor/lockstep/tokens.css": "design/tokens.css",
  "vendor/lockstep/lockstep.json": "contract/lockstep.json",
};
const sha = (b) => createHash("sha256").update(b).digest("hex");
const out = {};
for (const [to, from] of Object.entries(files)) {
  const b = readFileSync(root + from);
  writeFileSync(`${dest}/${to}`, b);
  out[to] = sha(b);
}
const doc = JSON.parse(readFileSync(root + "contract/lockstep.json", "utf8"));
// JS modules of the same data, so a Worker bundle and plain Node import them the same way.
const { newUserHintsHtml } = await import(root + "src/mesh-onboard.js");
const gen = {
  "vendor/lockstep/pinned.js": "/** GENERATED by aziel-runtime scripts/lockstep-vendor.mjs from contract/lockstep.json. Do not edit. */\nexport const PINNED = " + JSON.stringify(doc) + ";\n",
  "vendor/lockstep/tokens.js": "/** GENERATED by aziel-runtime scripts/lockstep-vendor.mjs from design/tokens.json. Do not edit. */\nexport const TOKENS = " + readFileSync(root + "design/tokens.json", "utf8").trim() + ";\n",
  "vendor/lockstep/hints-html.js": "/** GENERATED by aziel-runtime scripts/lockstep-vendor.mjs from src/mesh-onboard.js newUserHintsHtml(). Do not edit. */\nexport const HINTS_HTML = " + JSON.stringify(newUserHintsHtml()) + ";\n",
};
for (const [to, body] of Object.entries(gen)) {
  writeFileSync(`${dest}/${to}`, body);
  out[to] = sha(Buffer.from(body));
}
let commit = null;
try { commit = execSync("git rev-parse HEAD", { cwd: root }).toString().trim(); } catch {}
const pin = {
  spec: doc.spec,
  runtime_repo: "AzielEliab/aziel-runtime",
  runtime_commit: commit,
  runtime_version: doc.contract.runtime.version,
  contract_sha256: doc.contract_sha256,
  tokens_sha256: doc.tokens_sha256,
  css_sha256: doc.css_sha256,
  hints_sha256: doc.hints_sha256,
  files: out,
};
writeFileSync(`${dest}/LOCKSTEP.pin.json`, JSON.stringify(pin, null, 2) + "\n");
console.log(`vendored into ${dest}: contract ${pin.contract_sha256.slice(0, 12)}`);
