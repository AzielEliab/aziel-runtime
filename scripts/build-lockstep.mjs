/**
 * AZ-LOCKSTEP-1.0 build: design/tokens.json -> src/lockstep/design-tokens.js + design/tokens.css,
 * then contract/lockstep.json from the runtime code. Run after any change to tokens, locks, flags,
 * doors, chains, mesh, or the feature union:  npm run lockstep:build
 * Then re-vendor in AZInterface and AZ-OS:  node scripts/lockstep-vendor.mjs <runtime checkout>
 * Author: Aziel Eliab.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const tokens = JSON.parse(readFileSync(root + "design/tokens.json", "utf8"));
writeFileSync(
  root + "src/lockstep/design-tokens.js",
  "/** GENERATED by scripts/build-lockstep.mjs from design/tokens.json. Do not edit by hand. */\nexport const DESIGN_TOKENS = Object.freeze(" + JSON.stringify(tokens, null, 2) + ");\n",
);
const { tokensCss } = await import(root + "src/lockstep/tokens-css.js");
writeFileSync(root + "design/tokens.css", tokensCss(tokens));
const { PRODUCTS } = await import(root + "src/index.js");
const { lockstepDocument } = await import(root + "src/lockstep/contract.js");
const doc = await lockstepDocument(PRODUCTS);
const { hostDataFinding } = await import(root + "scripts/lockstep-hostscan.mjs");
const body = JSON.stringify(doc, null, 2) + "\n";
const leak = hostDataFinding(body) || hostDataFinding(readFileSync(root + "design/tokens.css", "utf8"));
if (leak) {
  console.error(`lockstep build refused: host-specific data in the generated contract (${leak}). Remove it from the source; nothing written.`);
  process.exit(1);
}
writeFileSync(root + "contract/lockstep.json", body);
console.log(`lockstep built: contract ${doc.contract_sha256} tokens ${doc.tokens_sha256} css ${doc.css_sha256}`);
