import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import "../src/index.js";
const R = await import("../src/offline-records.js");
const ops = await import("../src/chainlock/ops.js");
const d1 = await mkdtemp(join(tmpdir(), "azrec-")), d2 = await mkdtemp(join(tmpdir(), "azrec-"));
let s1 = await R.localStore(d1);
assert.equal((await ops.append(s1, { c: "session", f: "one" })).ok, true);
assert.equal((await ops.append(s1, { c: "session", f: "two" })).ok, true);
s1 = await R.localStore(d1); // restart: records persist
assert.equal((await ops.loadChain(s1, "session", "")).length, 2);
assert.equal((await ops.verify(s1, {})).ok, true);
const b = await R.exportBundle(s1, d1);
assert.equal((await R.checkBundle(b)).ok, true); assert.equal(b.signer_is_origin, false);
const s2 = await R.localStore(d2);
assert.equal((await R.importBundle(s2, b)).code, "OFFLINE-IMPORTED");
assert.equal((await R.importBundle(s2, b)).written, false);
assert.equal((await ops.verify(await R.localStore(d2), {})).ok, true);
const t = JSON.parse(JSON.stringify(b)); t.chains.session[1].fact = "x";
assert.equal((await R.importBundle(s2, t)).code, "OFFLINE-HASH-MISMATCH");
const forged = await R.signBundle(t.chains, d1, { source: "x" });
assert.equal((await R.checkBundle(forged)).code, "OFFLINE-CHAIN-BROKEN");
assert.equal((await R.importBundle(s2, b, { trustKeys: ["nope"] })).code, "OFFLINE-UNTRUSTED-SIGNER");
await ops.append(s2, { c: "session", f: "fork" });
await ops.append(s1, { c: "session", f: "three" });
assert.equal((await R.importBundle(s2, await R.exportBundle(s1, d1))).code, "OFFLINE-FORK");
assert.equal((await R.verifyAnchorsOffline("", null)).ok, false);
console.log("verify-offline-records: ok");
{
  const home = await mkdtemp(join(tmpdir(), "azmcp-"));
  process.env.AZIEL_RUNTIME_HOME = home;
  const { createLocalSend } = await import("../src/mcp-stdio.js");
  const send = await createLocalSend();
  const call = async (id, method, params) => (await send({ jsonrpc: "2.0", id, method, params }, {})).json();
  await call(1, "initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "t", version: "1" } });
  const r = await call(2, "tools/call", { name: "chainlock_append", arguments: { c: "session", f: "persisted via mcp local", confirm: true } });
  assert.notEqual(r.result && r.result.isError, true);
  const again = await R.localStore(join(home, "records"));
  assert.equal((await ops.loadChain(again, "session", "")).length, 1);
  delete process.env.AZIEL_RUNTIME_HOME;
  console.log("verify-offline-records: mcp local persists ok");
}
