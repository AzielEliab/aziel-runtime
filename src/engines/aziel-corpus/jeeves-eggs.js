export function normalizeJeevesRepeat(text) {
  return String(text || "")
    .trim()
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ");
}

export function isJeevesRepeat(question, previous) {
  const a = normalizeJeevesRepeat(question);
  const b = normalizeJeevesRepeat(previous);
  return Boolean(a && b && a === b);
}

